"""
Turn the McMaster crest into the ASCII behind the homepage hero.

    py scripts/make-ascii.py path/to/crest.png [columns]

Writes src/data/logo-ascii.ts. Columns default to 78. Characters are about
twice as tall as they are wide, so the row count follows the picture.
"""
import sys
from pathlib import Path

from PIL import Image

CHARS = {"G": "+", "M": "#", "K": "=", " ": " "}


def cell(r: int, g: int, b: int) -> str:
    mx, mn = max(r, g, b), min(r, g, b)
    sat = (mx - mn) / mx if mx else 0
    lum = (r + g + b) / 3
    if sat > 0.35 and r > 170 and g > 110:
        return "G"
    if r > 70 and r > g + 30 and r > b and g < 100:
        return "M"
    if sat < 0.18 and lum > 185:
        return " "
    if sat < 0.28 and 70 < lum < 185:
        return "K"
    return " "


def convert(path: str, cols: int = 78) -> list[str]:
    im = Image.open(path).convert("RGB")
    rows_n = max(1, round(im.height / im.width * cols * 0.46))
    small = im.resize((cols, rows_n), Image.Resampling.BOX)
    lines = ["".join(cell(*small.getpixel((x, y))) for x in range(cols)) for y in range(rows_n)]
    ys = [i for i, row in enumerate(lines) if row.strip()]
    xs = [x for x in range(cols) if any(row[x] != " " for row in lines)]
    if not ys or not xs:
        sys.exit("no crest pixels found")
    trimmed = [row[xs[0] : xs[-1] + 1].rstrip() for row in lines[ys[0] : ys[-1] + 1]]
    width = max(len(row) for row in trimmed)
    return ["".join(CHARS[c] for c in row.ljust(width)) for row in trimmed]


def write(rows: list[str], out: Path) -> None:
    body = ",\n".join(repr(row) for row in rows)
    out.write_text(
        "// Generated by scripts/make-ascii.py. Re-run it to change the crest.\n"
        "// '#' maroon, '+' gold, '=' the shield's grey edge.\n"
        f"export const LOGO_ASCII = [\n{body},\n] as const;\n",
        encoding="utf-8",
    )


if __name__ == "__main__":
    if len(sys.argv) < 2:
        sys.exit(__doc__)
    cols = int(sys.argv[2]) if len(sys.argv) > 2 else 78
    rows = convert(sys.argv[1], cols)
    out = Path(__file__).resolve().parent.parent / "src" / "data" / "logo-ascii.ts"
    write(rows, out)
    print(f"wrote {out} ({len(rows[0])} x {len(rows)})")
